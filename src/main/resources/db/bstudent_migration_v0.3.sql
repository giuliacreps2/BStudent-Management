-- =====================================================================
-- BStudent - migrazione v0.3 (PostgreSQL)
-- Applica alla v0.2: registrazione con conferma email e consenso del
-- genitore/tutore per gli studenti sotto i 14 anni (GDPR art. 8,
-- art. 2-quinquies Codice privacy).
-- I dati restano in registration_requests finche' non arriva la conferma:
-- solo allora nascono users/students/guardian_links. Richieste scadute o
-- rifiutate vengono cancellate definitivamente.
-- Transazionale e rieseguibile.
-- =====================================================================
BEGIN;

-- ---------------------------------------------------------------------
-- 1. Richieste di registrazione in attesa di conferma o consenso
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS registration_requests (
  registration_request_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_normalized          varchar(320) NOT NULL,
  password_hash             text         NOT NULL,
  first_name                varchar(100),
  last_name                 varchar(100),
  birth_date                date         NOT NULL,
  username                  varchar(80)  NOT NULL,
  school_id                 bigint       REFERENCES schools (school_id) ON DELETE SET NULL,
  requires_guardian_consent boolean      NOT NULL,
  guardian_email_normalized varchar(320),
  policy_version            varchar(40)  NOT NULL,
  token_hash                text         NOT NULL UNIQUE,
  status                    text         NOT NULL DEFAULT 'pending',
  expires_at                timestamptz  NOT NULL,
  send_count                smallint     NOT NULL DEFAULT 1,
  last_sent_at              timestamptz,
  created_at                timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE registration_requests DROP CONSTRAINT IF EXISTS chk_registration_requests_guardian;
ALTER TABLE registration_requests ADD  CONSTRAINT chk_registration_requests_guardian
  CHECK (requires_guardian_consent = (guardian_email_normalized IS NOT NULL));

ALTER TABLE registration_requests DROP CONSTRAINT IF EXISTS chk_registration_requests_guardian_email;
ALTER TABLE registration_requests ADD  CONSTRAINT chk_registration_requests_guardian_email
  CHECK (guardian_email_normalized IS NULL OR guardian_email_normalized <> email_normalized);

ALTER TABLE registration_requests DROP CONSTRAINT IF EXISTS chk_registration_requests_expiry;
ALTER TABLE registration_requests ADD  CONSTRAINT chk_registration_requests_expiry
  CHECK (expires_at > created_at);

ALTER TABLE registration_requests DROP CONSTRAINT IF EXISTS chk_registration_requests_send_count;
ALTER TABLE registration_requests ADD  CONSTRAINT chk_registration_requests_send_count
  CHECK (send_count > 0);

ALTER TABLE registration_requests DROP CONSTRAINT IF EXISTS chk_registration_requests_status_format;
ALTER TABLE registration_requests ADD  CONSTRAINT chk_registration_requests_status_format
  CHECK (status ~ '^[a-z][a-z0-9_]*$');

-- Una sola richiesta aperta per email e per username
CREATE UNIQUE INDEX IF NOT EXISTS uq_open_registration_requests_email
  ON registration_requests (email_normalized) WHERE status = 'pending';
CREATE UNIQUE INDEX IF NOT EXISTS uq_open_registration_requests_username
  ON registration_requests (username) WHERE status = 'pending';

-- Pulizia periodica delle richieste scadute
CREATE INDEX IF NOT EXISTS idx_registration_requests_expiry ON registration_requests (expires_at);

-- ---------------------------------------------------------------------
-- 2. guardian_links: prova del consenso (GDPR art. 7.1)
-- ---------------------------------------------------------------------
ALTER TABLE guardian_links ADD COLUMN IF NOT EXISTS consent_document_version varchar(40);

-- Un legame verificato deve dire quando e su quale versione e' stato dato il consenso
ALTER TABLE guardian_links DROP CONSTRAINT IF EXISTS chk_guardian_links_consent;
ALTER TABLE guardian_links ADD  CONSTRAINT chk_guardian_links_consent
  CHECK (verification_status <> 'verified'
         OR (verified_at IS NOT NULL AND consent_document_version IS NOT NULL));

-- ---------------------------------------------------------------------
-- 3. Ruoli usati dalla registrazione
-- ---------------------------------------------------------------------
INSERT INTO roles (code) VALUES ('ADMIN'), ('TEACHER'), ('STUDENT'), ('GUARDIAN')
ON CONFLICT (code) DO NOTHING;

COMMIT;
