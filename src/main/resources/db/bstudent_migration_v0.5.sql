-- =====================================================================
-- BStudent - migrazione v0.5 (PostgreSQL)
-- Applica alla v0.4: pagamenti e abbonamenti (Stripe) e contenuti freemium.
-- - Chi paga e' sempre un adulto (payer_user_id): lo studente dai 18 anni
--   o il genitore/tutore; i beneficiari sono studenti (max 2 nel piano famiglia).
-- - Nessun dato di carta: solo gli identificativi Stripe.
-- - Pagamenti, rimborsi e recessi si conservano 10 anni (art. 2220 c.c.):
--   le FK verso users/students sono RESTRICT, gli utenti si cancellano
--   solo logicamente (users.deleted_at).
-- - Importi in centesimi di euro; campi fiscali pronti per l'uscita dal
--   regime forfettario o per l'OSS (oggi aliquota 0).
-- Transazionale e rieseguibile.
-- =====================================================================
BEGIN;

-- ---------------------------------------------------------------------
-- 1. Contenuti freemium
-- ---------------------------------------------------------------------
-- Premium di default: un contenuto nuovo resta riservato finche' non lo si
-- segna 'free'. Gli utenti beta vedono tutto grazie agli access_grants.
ALTER TABLE courses ADD COLUMN IF NOT EXISTS access_tier text NOT NULL DEFAULT 'premium';
-- NULL = eredita dal corso; permette es. le prime missioni gratuite di un corso premium
ALTER TABLE missions ADD COLUMN IF NOT EXISTS access_tier text;

ALTER TABLE courses  DROP CONSTRAINT IF EXISTS chk_courses_access_tier_format;
ALTER TABLE courses  ADD  CONSTRAINT chk_courses_access_tier_format  CHECK (access_tier ~ '^[a-z][a-z0-9_]*$');
ALTER TABLE missions DROP CONSTRAINT IF EXISTS chk_missions_access_tier_format;
ALTER TABLE missions ADD  CONSTRAINT chk_missions_access_tier_format CHECK (access_tier ~ '^[a-z][a-z0-9_]*$');

-- ---------------------------------------------------------------------
-- 2. Catalogo: piani di abbonamento e prodotti singoli
-- ---------------------------------------------------------------------
-- Righe immutabili: un nuovo prezzo e' un nuovo piano, cosi' ogni contratto
-- conserva il prezzo con cui e' stato concluso
CREATE TABLE IF NOT EXISTS subscription_plans (
  plan_id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              varchar(60)  NOT NULL,
  name              text         NOT NULL,
  billing_interval  text         NOT NULL,
  -- 1 = individuale, 2 = famiglia (massimo 2 figli)
  max_students      smallint     NOT NULL DEFAULT 1,
  -- Prezzo finale pagato dall'utente (IVA inclusa quando applicabile)
  price_cents       integer      NOT NULL,
  currency          varchar(3)   NOT NULL DEFAULT 'EUR',
  -- Price di Stripe (price_...): NULL finche' il piano non e' configurato su Stripe
  provider_price_id text,
  active            boolean      NOT NULL DEFAULT true,
  valid_from        timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  valid_to          timestamptz,
  created_at        timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_subscription_plans_code           UNIQUE (code),
  CONSTRAINT uq_subscription_plans_provider_price UNIQUE (provider_price_id),
  CONSTRAINT chk_subscription_plans_interval_format CHECK (billing_interval ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_subscription_plans_max_students  CHECK (max_students BETWEEN 1 AND 2),
  CONSTRAINT chk_subscription_plans_price         CHECK (price_cents > 0),
  CONSTRAINT chk_subscription_plans_currency      CHECK (currency ~ '^[A-Z]{3}$'),
  CONSTRAINT chk_subscription_plans_validity      CHECK (valid_to IS NULL OR valid_to > valid_from)
);

-- Acquisti singoli futuri: solo articoli estetici (niente vantaggi nello studio)
CREATE TABLE IF NOT EXISTS products (
  product_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code              varchar(60)  NOT NULL,
  name              text         NOT NULL,
  description       text,
  kind              text         NOT NULL,
  price_cents       integer      NOT NULL,
  currency          varchar(3)   NOT NULL DEFAULT 'EUR',
  provider_price_id text,
  active            boolean      NOT NULL DEFAULT true,
  created_at        timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_products_code           UNIQUE (code),
  CONSTRAINT uq_products_provider_price UNIQUE (provider_price_id),
  CONSTRAINT chk_products_kind_format   CHECK (kind ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_products_price         CHECK (price_cents > 0),
  CONSTRAINT chk_products_currency      CHECK (currency ~ '^[A-Z]{3}$')
);

-- ---------------------------------------------------------------------
-- 3. Cliente di fatturazione (sempre un adulto)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS billing_customers (
  billing_customer_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id              bigint       NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
  provider             text         NOT NULL,
  provider_customer_id text         NOT NULL,
  -- Paese del cliente: determina il trattamento IVA (OSS sopra la soglia UE)
  country_code         varchar(2)   NOT NULL DEFAULT 'IT',
  -- Solo per chi chiede la fattura
  billing_name         text,
  billing_address      text,
  tax_code             varchar(16),
  created_at           timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at           timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_billing_customers_user     UNIQUE (user_id),
  CONSTRAINT uq_billing_customers_provider UNIQUE (provider, provider_customer_id),
  CONSTRAINT chk_billing_customers_provider_format CHECK (provider ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_billing_customers_country CHECK (country_code ~ '^[A-Z]{2}$')
);

-- ---------------------------------------------------------------------
-- 4. Sconti (es. utenti beta) e utilizzi
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS discounts (
  discount_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code               varchar(60)  NOT NULL,
  description        text         NOT NULL,
  -- A chi e' riservato: 'beta' = solo utenti con un access_grant beta
  audience           text         NOT NULL,
  percent_off        smallint,
  amount_off_cents   integer,
  -- once / repeating (per duration_in_months) / forever, come i coupon Stripe
  duration           text         NOT NULL,
  duration_in_months smallint,
  provider_coupon_id text,
  valid_from         timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  valid_until        timestamptz,
  max_redemptions    integer,
  active             boolean      NOT NULL DEFAULT true,
  created_at         timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_discounts_code            UNIQUE (code),
  CONSTRAINT uq_discounts_provider_coupon UNIQUE (provider_coupon_id),
  CONSTRAINT chk_discounts_audience_format CHECK (audience ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_discounts_duration_format CHECK (duration ~ '^[a-z][a-z0-9_]*$'),
  -- Esattamente uno tra percentuale e importo fisso
  CONSTRAINT chk_discounts_amount CHECK (
    (percent_off IS NOT NULL AND percent_off BETWEEN 1 AND 100 AND amount_off_cents IS NULL)
    OR (amount_off_cents IS NOT NULL AND amount_off_cents > 0 AND percent_off IS NULL)),
  CONSTRAINT chk_discounts_months CHECK ((duration = 'repeating') = (duration_in_months IS NOT NULL)),
  CONSTRAINT chk_discounts_months_positive CHECK (duration_in_months IS NULL OR duration_in_months > 0),
  CONSTRAINT chk_discounts_validity CHECK (valid_until IS NULL OR valid_until > valid_from),
  CONSTRAINT chk_discounts_max_redemptions CHECK (max_redemptions IS NULL OR max_redemptions > 0)
);

-- ---------------------------------------------------------------------
-- 5. Abbonamenti e studenti coperti
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS subscriptions (
  subscription_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payer_user_id              bigint       NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
  plan_id                    bigint       NOT NULL REFERENCES subscription_plans (plan_id) ON DELETE RESTRICT,
  -- Stati di Stripe (incomplete, active, past_due, canceled, ...)
  status                     text         NOT NULL,
  -- NULL finche' il checkout non e' completato
  provider_subscription_id   text,
  started_at                 timestamptz,
  current_period_start       timestamptz,
  current_period_end         timestamptz,
  -- Disdetta: niente rinnovo, accesso fino alla fine del periodo pagato
  cancel_at_period_end       boolean      NOT NULL DEFAULT false,
  canceled_at                timestamptz,
  ended_at                   timestamptz,
  end_reason                 text,
  -- Recesso entro 14 giorni dalla conclusione (art. 52 Codice del consumo)
  withdrawal_deadline        timestamptz,
  -- Richiesta di esecuzione immediata: in caso di recesso si paga la parte gia' fruita (art. 57 c. 3)
  immediate_start_consent_at timestamptz,
  -- Versione delle condizioni di vendita accettate (anche in policy_acceptances)
  terms_version              varchar(40)  NOT NULL,
  -- Promemoria prima del rinnovo dei piani annuali
  renewal_reminder_sent_at   timestamptz,
  created_at                 timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                 timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_subscriptions_provider UNIQUE (provider_subscription_id),
  CONSTRAINT chk_subscriptions_status_format     CHECK (status ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_subscriptions_end_reason_format CHECK (end_reason ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_subscriptions_period CHECK (current_period_end IS NULL OR current_period_start IS NULL
                                             OR current_period_end > current_period_start),
  CONSTRAINT chk_subscriptions_ended  CHECK (ended_at IS NULL OR end_reason IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS idx_subscriptions_payer ON subscriptions (payer_user_id);
-- Ricerca dei piani annuali da avvisare prima del rinnovo
CREATE INDEX IF NOT EXISTS idx_subscriptions_period_end ON subscriptions (current_period_end)
  WHERE ended_at IS NULL;

-- Studenti coperti da un abbonamento; il massimo (plans.max_students) lo verifica il service
CREATE TABLE IF NOT EXISTS subscription_students (
  subscription_student_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subscription_id         bigint       NOT NULL REFERENCES subscriptions (subscription_id) ON DELETE RESTRICT,
  student_id              bigint       NOT NULL REFERENCES students (student_id) ON DELETE RESTRICT,
  added_at                timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- Valorizzato quando lo studente esce dal piano o l'abbonamento termina
  removed_at              timestamptz,
  CONSTRAINT chk_subscription_students_removed CHECK (removed_at IS NULL OR removed_at >= added_at)
);
CREATE INDEX IF NOT EXISTS idx_subscription_students_subscription ON subscription_students (subscription_id);
-- Uno studente e' coperto da un solo abbonamento alla volta
CREATE UNIQUE INDEX IF NOT EXISTS uq_open_subscription_students_student
  ON subscription_students (student_id) WHERE removed_at IS NULL;

CREATE TABLE IF NOT EXISTS discount_redemptions (
  discount_redemption_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discount_id            bigint       NOT NULL REFERENCES discounts (discount_id) ON DELETE RESTRICT,
  user_id                bigint       NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
  subscription_id        bigint       REFERENCES subscriptions (subscription_id) ON DELETE RESTRICT,
  redeemed_at            timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- Ogni sconto si usa una volta per persona
  CONSTRAINT uq_discount_redemptions_user UNIQUE (discount_id, user_id)
);

-- ---------------------------------------------------------------------
-- 6. Ordini singoli (prodotti), pagamenti, rimborsi, recessi
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS product_orders (
  product_order_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payer_user_id                bigint       NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
  student_id                   bigint       NOT NULL REFERENCES students (student_id) ON DELETE RESTRICT,
  product_id                   bigint       NOT NULL REFERENCES products (product_id) ON DELETE RESTRICT,
  status                       text         NOT NULL,
  amount_cents                 integer      NOT NULL,
  currency                     varchar(3)   NOT NULL DEFAULT 'EUR',
  provider_checkout_session_id text,
  withdrawal_deadline          timestamptz,
  immediate_start_consent_at   timestamptz,
  terms_version                varchar(40)  NOT NULL,
  created_at                   timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  paid_at                      timestamptz,
  CONSTRAINT uq_product_orders_checkout UNIQUE (provider_checkout_session_id),
  CONSTRAINT chk_product_orders_status_format CHECK (status ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_product_orders_amount   CHECK (amount_cents > 0),
  CONSTRAINT chk_product_orders_currency CHECK (currency ~ '^[A-Z]{3}$')
);
CREATE INDEX IF NOT EXISTS idx_product_orders_payer   ON product_orders (payer_user_id);
CREATE INDEX IF NOT EXISTS idx_product_orders_student ON product_orders (student_id);

-- Un pagamento per riga: primo addebito, ogni rinnovo, conguagli, ordini singoli
CREATE TABLE IF NOT EXISTS payments (
  payment_id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payer_user_id             bigint       NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
  subscription_id           bigint       REFERENCES subscriptions (subscription_id) ON DELETE RESTRICT,
  product_order_id          bigint       REFERENCES product_orders (product_order_id) ON DELETE RESTRICT,
  kind                      text         NOT NULL,
  status                    text         NOT NULL,
  -- Importo lordo addebitato, gia' al netto dello sconto
  amount_cents              integer      NOT NULL,
  discount_cents            integer      NOT NULL DEFAULT 0,
  -- Oggi 0: regime forfettario, IVA non applicata
  tax_cents                 integer      NOT NULL DEFAULT 0,
  tax_rate_bps              integer      NOT NULL DEFAULT 0,
  tax_treatment             text         NOT NULL,
  customer_country          varchar(2)   NOT NULL DEFAULT 'IT',
  currency                  varchar(3)   NOT NULL DEFAULT 'EUR',
  period_start              timestamptz,
  period_end                timestamptz,
  paid_at                   timestamptz,
  failure_code              text,
  provider_invoice_id       text,
  provider_payment_intent_id text,
  -- Fattura emessa su richiesta (software del commercialista)
  invoice_number            varchar(40),
  invoice_issued_at         timestamptz,
  created_at                timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_payments_provider_invoice UNIQUE (provider_invoice_id),
  CONSTRAINT uq_payments_provider_intent  UNIQUE (provider_payment_intent_id),
  -- Ogni pagamento appartiene a un abbonamento oppure a un ordine singolo
  CONSTRAINT chk_payments_owner CHECK ((subscription_id IS NULL) <> (product_order_id IS NULL)),
  CONSTRAINT chk_payments_kind_format     CHECK (kind ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_payments_status_format   CHECK (status ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_payments_tax_format      CHECK (tax_treatment ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_payments_amounts CHECK (amount_cents >= 0 AND discount_cents >= 0
                                         AND tax_cents >= 0 AND tax_cents <= amount_cents),
  CONSTRAINT chk_payments_tax_rate CHECK (tax_rate_bps BETWEEN 0 AND 10000),
  CONSTRAINT chk_payments_country  CHECK (customer_country ~ '^[A-Z]{2}$'),
  CONSTRAINT chk_payments_currency CHECK (currency ~ '^[A-Z]{3}$'),
  CONSTRAINT chk_payments_period   CHECK (period_end IS NULL OR period_start IS NULL OR period_end > period_start)
);
CREATE INDEX IF NOT EXISTS idx_payments_subscription  ON payments (subscription_id);
CREATE INDEX IF NOT EXISTS idx_payments_product_order ON payments (product_order_id);
CREATE INDEX IF NOT EXISTS idx_payments_payer         ON payments (payer_user_id);

CREATE TABLE IF NOT EXISTS refunds (
  refund_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id         bigint       NOT NULL REFERENCES payments (payment_id) ON DELETE RESTRICT,
  amount_cents       integer      NOT NULL,
  reason             text         NOT NULL,
  status             text         NOT NULL,
  provider_refund_id text,
  created_at         timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  processed_at       timestamptz,
  CONSTRAINT uq_refunds_provider UNIQUE (provider_refund_id),
  CONSTRAINT chk_refunds_amount CHECK (amount_cents > 0),
  CONSTRAINT chk_refunds_reason_format CHECK (reason ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_refunds_status_format CHECK (status ~ '^[a-z][a-z0-9_]*$')
);
CREATE INDEX IF NOT EXISTS idx_refunds_payment ON refunds (payment_id);

-- Prova del recesso (art. 54-bis Codice del consumo, funzione "recedi dal contratto qui")
CREATE TABLE IF NOT EXISTS withdrawal_requests (
  withdrawal_request_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subscription_id       bigint       REFERENCES subscriptions (subscription_id) ON DELETE RESTRICT,
  product_order_id      bigint       REFERENCES product_orders (product_order_id) ON DELETE RESTRICT,
  requested_by_user_id  bigint       NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
  requested_at          timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- Conferma su supporto durevole (email)
  confirmation_sent_at  timestamptz,
  -- Parte trattenuta per il servizio gia' fruito
  retained_amount_cents integer      NOT NULL DEFAULT 0,
  refund_id             bigint       REFERENCES refunds (refund_id) ON DELETE RESTRICT,
  CONSTRAINT uq_withdrawal_requests_refund UNIQUE (refund_id),
  CONSTRAINT chk_withdrawal_requests_owner CHECK ((subscription_id IS NULL) <> (product_order_id IS NULL)),
  CONSTRAINT chk_withdrawal_requests_retained CHECK (retained_amount_cents >= 0)
);
-- Un solo recesso per contratto
CREATE UNIQUE INDEX IF NOT EXISTS uq_withdrawal_requests_subscription
  ON withdrawal_requests (subscription_id) WHERE subscription_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_withdrawal_requests_product_order
  ON withdrawal_requests (product_order_id) WHERE product_order_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- 7. Accessi premium senza pagamento (beta, promozioni, staff)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS access_grants (
  access_grant_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id         bigint       NOT NULL REFERENCES students (student_id) ON DELETE CASCADE,
  source             text         NOT NULL,
  starts_at          timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  -- NULL = senza scadenza (es. staff)
  ends_at            timestamptz,
  granted_by_user_id bigint       REFERENCES users (user_id) ON DELETE SET NULL,
  revoked_at         timestamptz,
  note               text,
  created_at         timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_access_grants_source_format CHECK (source ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_access_grants_period CHECK (ends_at IS NULL OR ends_at > starts_at)
);
CREATE INDEX IF NOT EXISTS idx_access_grants_student ON access_grants (student_id);

-- ---------------------------------------------------------------------
-- 8. Richieste di acquisto dello studente minorenne al genitore/tutore
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS purchase_requests (
  purchase_request_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id                bigint       NOT NULL REFERENCES students (student_id) ON DELETE CASCADE,
  invitee_email_normalized  varchar(320) NOT NULL,
  -- Valorizzato quando il genitore/tutore apre il link con il suo account
  guardian_user_id          bigint       REFERENCES users (user_id) ON DELETE SET NULL,
  plan_id                   bigint       REFERENCES subscription_plans (plan_id) ON DELETE RESTRICT,
  product_id                bigint       REFERENCES products (product_id) ON DELETE RESTRICT,
  status                    text         NOT NULL,
  -- Solo l'hash SHA-256: il token in chiaro esiste solo nell'email
  token_hash                text         NOT NULL,
  expires_at                timestamptz  NOT NULL,
  created_at                timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at               timestamptz,
  CONSTRAINT uq_purchase_requests_token UNIQUE (token_hash),
  -- Si chiede un piano oppure un prodotto
  CONSTRAINT chk_purchase_requests_item CHECK ((plan_id IS NULL) <> (product_id IS NULL)),
  CONSTRAINT chk_purchase_requests_status_format CHECK (status ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT chk_purchase_requests_expiry CHECK (expires_at > created_at)
);
CREATE INDEX IF NOT EXISTS idx_purchase_requests_expiry ON purchase_requests (expires_at);
-- Una sola richiesta aperta per studente: niente insistenza verso il genitore
CREATE UNIQUE INDEX IF NOT EXISTS uq_open_purchase_requests_student
  ON purchase_requests (student_id) WHERE status = 'pending';

-- ---------------------------------------------------------------------
-- 9. Webhook ricevuti (idempotenza e audit)
-- ---------------------------------------------------------------------
-- Nessun payload: contiene dati personali e Stripe permette di rileggere l'evento per id
CREATE TABLE IF NOT EXISTS billing_events (
  billing_event_id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider          text         NOT NULL,
  provider_event_id text         NOT NULL,
  event_type        text         NOT NULL,
  -- Oggetto Stripe interessato (sub_..., in_..., ch_...)
  object_id         text,
  received_at       timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP,
  processed_at      timestamptz,
  processing_error  text,
  CONSTRAINT uq_billing_events_provider UNIQUE (provider, provider_event_id),
  CONSTRAINT chk_billing_events_provider_format CHECK (provider ~ '^[a-z][a-z0-9_]*$')
);
-- Eventi da rielaborare
CREATE INDEX IF NOT EXISTS idx_billing_events_unprocessed ON billing_events (received_at)
  WHERE processed_at IS NULL;

COMMIT;
