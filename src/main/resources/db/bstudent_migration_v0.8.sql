-- =====================================================================
-- BStudent - migrazione v0.8 (PostgreSQL)
-- Applica alla v0.7: sequenza libera della missione.
-- - mission_steps: la missione e' una sequenza ordinata di passi, ognuno
--   e' una lezione OPPURE un esercizio;
-- - gli esercizi di missione non appartengono piu' a una lezione
--   (mission_exercises.lesson_id eliminata);
-- - l'ordine delle lezioni vive nei passi (lessons.sort_order eliminata);
-- - stato draft/published dell'esercizio nella missione.
-- Regole della sequenza (nel service, coinvolgono piu' righe): inizia con
-- una lezione, due esercizi non si susseguono, almeno un esercizio per
-- pubblicare. Lo stesso esercizio non si ripete nella missione: lo
-- garantisce gia' UNIQUE (mission_id, question_bank_entry_id).
-- I dati esistenti diventano: ogni lezione nel suo ordine, seguita dal suo
-- esercizio se ne aveva uno.
-- Transazionale e rieseguibile.
-- =====================================================================
BEGIN;

-- ---------------------------------------------------------------------
-- 1. Target delle FK composte (passo, missione)
-- ---------------------------------------------------------------------
-- Il passo e la sua lezione/esercizio appartengono alla stessa missione.
-- lessons (lesson_id, mission_id) esiste gia' (non deferrable).
-- Creato solo se manca: dopo la prima esecuzione la FK di mission_steps ne dipende
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'uq_mission_exercises_id_mission') THEN
    ALTER TABLE mission_exercises ADD CONSTRAINT uq_mission_exercises_id_mission
      UNIQUE (mission_exercise_id, mission_id);
  END IF;
END $$;

-- ---------------------------------------------------------------------
-- 2. Passi della missione
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mission_steps (
  mission_step_id     bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mission_id          bigint  NOT NULL REFERENCES missions (mission_id) DEFERRABLE INITIALLY IMMEDIATE,
  sort_order          integer NOT NULL,
  lesson_id           bigint,
  mission_exercise_id bigint,
  CONSTRAINT chk_mission_steps_sort_order CHECK (sort_order > 0),
  -- Esattamente uno dei due
  CONSTRAINT chk_mission_steps_kind       CHECK (num_nonnulls(lesson_id, mission_exercise_id) = 1),
  -- Ogni lezione ed esercizio e' al massimo un passo
  CONSTRAINT uq_mission_steps_lesson   UNIQUE (lesson_id),
  CONSTRAINT uq_mission_steps_exercise UNIQUE (mission_exercise_id),
  CONSTRAINT fk_mission_steps_lesson_mission
    FOREIGN KEY (lesson_id, mission_id) REFERENCES lessons (lesson_id, mission_id) DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT fk_mission_steps_exercise_mission
    FOREIGN KEY (mission_exercise_id, mission_id) REFERENCES mission_exercises (mission_exercise_id, mission_id) DEFERRABLE INITIALLY IMMEDIATE,
  -- DEFERRABLE per il riordino atomico, come gli altri ordinamenti (v0.6)
  CONSTRAINT mission_steps_mission_id_sort_order_idx
    UNIQUE (mission_id, sort_order) DEFERRABLE INITIALLY IMMEDIATE
);

-- ---------------------------------------------------------------------
-- 3. Conversione dei dati esistenti
-- ---------------------------------------------------------------------
-- Solo alla prima esecuzione: dopo, lesson_id di mission_exercises non c'e' piu'.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns
              WHERE table_schema = 'public' AND table_name = 'mission_exercises' AND column_name = 'lesson_id') THEN
    INSERT INTO mission_steps (mission_id, sort_order, lesson_id, mission_exercise_id)
    SELECT mission_id,
           row_number() OVER (PARTITION BY mission_id ORDER BY lesson_sort, is_exercise),
           lesson_id, mission_exercise_id
      FROM (SELECT l.mission_id, l.sort_order AS lesson_sort, 0 AS is_exercise,
                   l.lesson_id, NULL::bigint AS mission_exercise_id
              FROM lessons l
            UNION ALL
            SELECT me.mission_id, l.sort_order, 1,
                   NULL::bigint, me.mission_exercise_id
              FROM mission_exercises me JOIN lessons l ON l.lesson_id = me.lesson_id) s;
  END IF;
END $$;

-- ---------------------------------------------------------------------
-- 4. Esercizi senza lezione, lezioni senza ordine proprio
-- ---------------------------------------------------------------------
-- Con la colonna vanno via anche la sua UNIQUE e le due FK verso lessons
ALTER TABLE mission_exercises DROP COLUMN IF EXISTS lesson_id;

-- Con la colonna vanno via anche lessons_mission_id_sort_order_idx e il CHECK
ALTER TABLE lessons DROP COLUMN IF EXISTS sort_order;

-- ---------------------------------------------------------------------
-- 5. Stato dell'esercizio nella missione
-- ---------------------------------------------------------------------
-- Il collegamento nasce draft: in una missione pubblicata resta nascosto
-- finche' l'Admin non lo pubblica (servono esercizio pubblicato e skill);
-- in una missione non pubblicata viene pubblicato insieme alla missione.
-- Nessun withdrawn: per nasconderlo si ritira l'esercizio nel banco o lo si scollega.
-- I collegamenti esistenti erano gia' visibili: partono published.
ALTER TABLE mission_exercises ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'published';
ALTER TABLE mission_exercises ALTER COLUMN status SET DEFAULT 'draft';
ALTER TABLE mission_exercises DROP CONSTRAINT IF EXISTS chk_mission_exercises_status;
ALTER TABLE mission_exercises ADD  CONSTRAINT chk_mission_exercises_status CHECK (status IN ('draft', 'published'));

COMMIT;
