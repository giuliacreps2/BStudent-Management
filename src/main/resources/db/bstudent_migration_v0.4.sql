-- =====================================================================
-- BStudent - migrazione v0.4 (PostgreSQL)
-- Applica alla v0.3: accesso con Google OAuth2 ("Google as Gateway").
-- - users.password_hash facoltativa: account solo Google, che possono
--   impostare una password locale con il flusso di reset;
-- - user_identities: identita' esterne collegate all'account (sub di Google);
-- - registration_requests: richieste dei minori arrivate da Google, senza
--   password ma con l'identita' Google da collegare alla conferma.
-- Transazionale e rieseguibile.
-- =====================================================================
BEGIN;

-- ---------------------------------------------------------------------
-- 1. Password locale facoltativa
-- ---------------------------------------------------------------------
-- "Almeno una credenziale" (password o identita' esterna) coinvolge due
-- tabelle: la garantisce il service, non un CHECK
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- ---------------------------------------------------------------------
-- 2. Identita' esterne
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_identities (
  user_identity_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id          bigint       NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
  provider         text         NOT NULL,
  -- "sub" di Google: stabile anche se l'utente cambia email
  provider_subject text         NOT NULL,
  -- Email comunicata dal provider al momento del collegamento (solo storico)
  email_at_link    varchar(320),
  created_at       timestamptz  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE user_identities DROP CONSTRAINT IF EXISTS chk_user_identities_provider_format;
ALTER TABLE user_identities ADD  CONSTRAINT chk_user_identities_provider_format
  CHECK (provider ~ '^[a-z][a-z0-9_]*$');

ALTER TABLE user_identities DROP CONSTRAINT IF EXISTS chk_user_identities_subject;
ALTER TABLE user_identities ADD  CONSTRAINT chk_user_identities_subject
  CHECK (btrim(provider_subject) <> '');

-- Un'identita' esterna appartiene a un solo account ...
ALTER TABLE user_identities DROP CONSTRAINT IF EXISTS uq_user_identities_subject;
ALTER TABLE user_identities ADD  CONSTRAINT uq_user_identities_subject UNIQUE (provider, provider_subject);
-- ... e un account ha al massimo un'identita' per provider (copre anche la ricerca per user_id)
ALTER TABLE user_identities DROP CONSTRAINT IF EXISTS uq_user_identities_user;
ALTER TABLE user_identities ADD  CONSTRAINT uq_user_identities_user UNIQUE (user_id, provider);

-- ---------------------------------------------------------------------
-- 3. Richieste di registrazione da Google (minori in attesa di consenso)
-- ---------------------------------------------------------------------
ALTER TABLE registration_requests ALTER COLUMN password_hash DROP NOT NULL;
ALTER TABLE registration_requests ADD COLUMN IF NOT EXISTS google_subject text;

-- Ogni richiesta porta con se' una credenziale: password locale o identita' Google
ALTER TABLE registration_requests DROP CONSTRAINT IF EXISTS chk_registration_requests_credential;
ALTER TABLE registration_requests ADD  CONSTRAINT chk_registration_requests_credential
  CHECK (password_hash IS NOT NULL OR google_subject IS NOT NULL);

-- Una sola richiesta aperta per identita' Google
CREATE UNIQUE INDEX IF NOT EXISTS uq_open_registration_requests_google
  ON registration_requests (google_subject) WHERE status = 'pending' AND google_subject IS NOT NULL;

-- ---------------------------------------------------------------------
-- 4. CHECK sugli enum generati da Hibernate (DB creati con ddl-auto=create/update)
-- ---------------------------------------------------------------------
-- Elencano i valori dell'enum al momento della generazione e restano indietro quando l'enum cambia
-- (es. users.status ammetteva solo 'pending_verification', guardian_links.relationship i vecchi
-- valori italiani maiuscoli). Su un DB creato dagli script SQL non esistono: i DROP non fanno nulla.
-- I valori ammessi li governa l'enum Java; il DB verifica il formato, come nella v0.2.
ALTER TABLE users           DROP CONSTRAINT IF EXISTS users_status_check;
ALTER TABLE guardian_links  DROP CONSTRAINT IF EXISTS guardian_links_relationship_check;
ALTER TABLE guardian_links  DROP CONSTRAINT IF EXISTS guardian_links_verification_status_check;
ALTER TABLE auth_tokens     DROP CONSTRAINT IF EXISTS auth_tokens_purpose_check;
ALTER TABLE user_identities DROP CONSTRAINT IF EXISTS user_identities_provider_check;

ALTER TABLE users          DROP CONSTRAINT IF EXISTS chk_users_status_format;
ALTER TABLE users          ADD  CONSTRAINT chk_users_status_format          CHECK (status ~ '^[a-z][a-z0-9_]*$');
ALTER TABLE guardian_links DROP CONSTRAINT IF EXISTS chk_guardian_links_status_format;
ALTER TABLE guardian_links ADD  CONSTRAINT chk_guardian_links_status_format CHECK (verification_status ~ '^[a-z][a-z0-9_]*$');
ALTER TABLE guardian_links DROP CONSTRAINT IF EXISTS chk_guardian_links_relationship_format;
ALTER TABLE guardian_links ADD  CONSTRAINT chk_guardian_links_relationship_format CHECK (relationship ~ '^[a-z][a-z0-9_]*$');
ALTER TABLE auth_tokens    DROP CONSTRAINT IF EXISTS chk_auth_tokens_purpose_format;
ALTER TABLE auth_tokens    ADD  CONSTRAINT chk_auth_tokens_purpose_format   CHECK (purpose ~ '^[a-z][a-z0-9_]*$');

COMMIT;
